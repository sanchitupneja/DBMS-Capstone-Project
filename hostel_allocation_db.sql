SELECT s.studentId, s.fullName, s.email, s.gender, s.course, s.yearOfStudy, r.roomNumber, h.name AS hostelName, al.status AS allocationStatus
FROM students s
LEFT JOIN allocations al ON al.studentId = s.id AND al.status = 'ACTIVE'
LEFT JOIN rooms r ON r.id = al.roomId
LEFT JOIN hostels h ON h.id = r.hostelId
ORDER BY s.studentId;

SELECT h.name, h.gender, h.totalRooms, h.availableRooms, h.totalRooms - h.availableRooms AS occupiedRooms, ROUND(((h.totalRooms - h.availableRooms) / h.totalRooms) * 100, 1) AS occupancyPercent
FROM hostels h;

SELECT h.name AS hostelName, r.roomNumber, r.floor, r.roomType, r.occupiedBeds, r.totalBeds, r.status, r.pricePerMonth
FROM rooms r
JOIN hostels h ON h.id = r.hostelId
ORDER BY h.name, r.roomNumber;

