CREATE DATABASE IF NOT EXISTS hostel_allocation_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE hostel_allocation_db;

CREATE TABLE IF NOT EXISTS `admins` (
  `id`           VARCHAR(36)  NOT NULL,
  `email`        VARCHAR(191) NOT NULL,
  `passwordHash` TEXT         NOT NULL,
  `fullName`     VARCHAR(191) NOT NULL,
  `role`         ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'ADMIN',
  `refreshToken` TEXT         NULL,
  `createdAt`    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `admins_email_key` (`email`),
  KEY `admins_email_idx` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `students` (
  `id`              VARCHAR(36)  NOT NULL,
  `email`           VARCHAR(191) NOT NULL,
  `passwordHash`    TEXT         NOT NULL,
  `fullName`        VARCHAR(191) NOT NULL,
  `studentId`       VARCHAR(100) NOT NULL,
  `phone`           VARCHAR(20)  NULL,
  `gender`          ENUM('MALE','FEMALE','OTHER') NOT NULL,
  `course`          VARCHAR(191) NOT NULL,
  `yearOfStudy`     INT          NOT NULL,
  `role`            ENUM('STUDENT','ADMIN') NOT NULL DEFAULT 'STUDENT',
  `profileImageUrl` TEXT         NULL,
  `isEmailVerified` TINYINT(1)   NOT NULL DEFAULT 0,
  `refreshToken`    TEXT         NULL,
  `createdAt`       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `students_email_key` (`email`),
  UNIQUE KEY `students_studentId_key` (`studentId`),
  KEY `students_email_idx` (`email`),
  KEY `students_studentId_idx` (`studentId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `hostels` (
  `id`             VARCHAR(36)  NOT NULL,
  `name`           VARCHAR(191) NOT NULL,
  `description`    TEXT         NULL,
  `gender`         ENUM('MALE','FEMALE','OTHER') NOT NULL,
  `address`        VARCHAR(300) NOT NULL,
  `totalRooms`     INT          NOT NULL DEFAULT 0,
  `availableRooms` INT          NOT NULL DEFAULT 0,
  `imageUrl`       TEXT         NULL,
  `amenities`      JSON         NOT NULL DEFAULT (JSON_ARRAY()),
  `isActive`       TINYINT(1)   NOT NULL DEFAULT 1,
  `createdAt`      DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`      DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `hostels_name_key` (`name`),
  KEY `hostels_gender_isActive_idx` (`gender`, `isActive`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `rooms` (
  `id`            VARCHAR(36) NOT NULL,
  `hostelId`      VARCHAR(36) NOT NULL,
  `roomNumber`    VARCHAR(20) NOT NULL,
  `floor`         INT         NOT NULL DEFAULT 0,
  `roomType`      ENUM('AC','NON_AC') NOT NULL,
  `totalBeds`     INT         NOT NULL,
  `occupiedBeds`  INT         NOT NULL DEFAULT 0,
  `status`        ENUM('AVAILABLE','PARTIALLY_OCCUPIED','FULL','UNDER_MAINTENANCE') NOT NULL DEFAULT 'AVAILABLE',
  `pricePerMonth` DOUBLE      NOT NULL,
  `amenities`     JSON        NOT NULL DEFAULT (JSON_ARRAY()),
  `createdAt`     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `rooms_hostelId_roomNumber_key` (`hostelId`, `roomNumber`),
  KEY `rooms_hostelId_status_idx` (`hostelId`, `status`),
  KEY `rooms_hostelId_roomType_status_idx` (`hostelId`, `roomType`, `status`),
  KEY `rooms_status_idx` (`status`),
  CONSTRAINT `rooms_hostelId_fkey` FOREIGN KEY (`hostelId`) REFERENCES `hostels` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `allocation_requests` (
  `id`                  VARCHAR(36) NOT NULL,
  `studentId`           VARCHAR(36) NOT NULL,
  `hostelId`            VARCHAR(36) NOT NULL,
  `preferredRoomType`   ENUM('AC','NON_AC') NOT NULL,
  `preferredFloor`      INT         NULL,
  `specialRequirements` TEXT        NULL,
  `status`              ENUM('PENDING','APPROVED','REJECTED','WAITLISTED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  `rejectionReason`     TEXT        NULL,
  `processedById`       VARCHAR(36) NULL,
  `processedAt`         DATETIME(3) NULL,
  `academicYear`        VARCHAR(20) NOT NULL,
  `semester`            INT         NOT NULL,
  `createdAt`           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`           DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `allocation_requests_studentId_academicYear_semester_key` (`studentId`, `academicYear`, `semester`),
  KEY `allocation_requests_status_createdAt_idx` (`status`, `createdAt`),
  KEY `allocation_requests_hostelId_status_idx` (`hostelId`, `status`),
  KEY `allocation_requests_studentId_status_idx` (`studentId`, `status`),
  CONSTRAINT `allocation_requests_studentId_fkey` FOREIGN KEY (`studentId`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  CONSTRAINT `allocation_requests_hostelId_fkey` FOREIGN KEY (`hostelId`) REFERENCES `hostels` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `allocation_requests_processedById_fkey` FOREIGN KEY (`processedById`) REFERENCES `admins` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `allocations` (
  `id`            VARCHAR(36) NOT NULL,
  `studentId`     VARCHAR(36) NOT NULL,
  `roomId`        VARCHAR(36) NOT NULL,
  `requestId`     VARCHAR(36) NOT NULL,
  `allocatedById` VARCHAR(36) NULL,
  `status`        ENUM('ACTIVE','VACATED','TRANSFERRED','EXPIRED') NOT NULL DEFAULT 'ACTIVE',
  `checkInDate`   DATETIME(3) NOT NULL,
  `checkOutDate`  DATETIME(3) NULL,
  `academicYear`  VARCHAR(20) NOT NULL,
  `semester`      INT         NOT NULL,
  `notes`         TEXT        NULL,
  `createdAt`     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt`     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `allocations_requestId_key` (`requestId`),
  UNIQUE KEY `allocations_studentId_status_academicYear_semester_key` (`studentId`, `status`, `academicYear`, `semester`),
  KEY `allocations_roomId_status_idx` (`roomId`, `status`),
  KEY `allocations_studentId_status_idx` (`studentId`, `status`),
  KEY `allocations_academicYear_semester_idx` (`academicYear`, `semester`),
  CONSTRAINT `allocations_studentId_fkey` FOREIGN KEY (`studentId`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  CONSTRAINT `allocations_roomId_fkey` FOREIGN KEY (`roomId`) REFERENCES `rooms` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `allocations_requestId_fkey` FOREIGN KEY (`requestId`) REFERENCES `allocation_requests` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `allocations_allocatedById_fkey` FOREIGN KEY (`allocatedById`) REFERENCES `admins` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

